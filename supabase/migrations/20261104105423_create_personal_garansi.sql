create table if not exists public.personal_garansi (
  id bigint generated by default as identity primary key,
  tanggal date not null default current_date,
  penjamin text not null,
  pekerjaan text,
  no_ktp text not null,
  investor text not null,
  nominal numeric(18,2) not null default 0 check (nominal >= 0),
  saksi_1 text,
  saksi_2 text,
  dibuat_di text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.personal_garansi enable row level security;
grant select, insert, update, delete on public.personal_garansi to authenticated;
grant usage, select on sequence public.personal_garansi_id_seq to authenticated;
drop policy if exists "PilotX admin email manages personal garansi" on public.personal_garansi;
create policy "PilotX admin email manages personal garansi"
on public.personal_garansi
for all
to authenticated
using ((auth.jwt() ->> 'email') = 'admin@pilotx.com')
with check ((auth.jwt() ->> 'email') = 'admin@pilotx.com');